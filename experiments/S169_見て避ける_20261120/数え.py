def 別々(o, lo, hi):
    A, 物, 手 = o['行動列'], o['物'], o['手がかり']; t = np.arange(lo, hi); t = t[t % 2 == 0]; A, 物, 手 = A[t], 物[t], 手[t]; 取 = A == 0; m = 手 == 0
    return float(取[m & (物 == 1)].mean()), float(取[m & (物 == -1)].mean())
def 痛い目(o, 始め=4000, 終わり=4600):
    A, 物 = o['行動列'][始め:], o['物'][始め:]; 悪取 = (A == 0) & (物 == -1); 初 = []
    for i in range(A.shape[1]):
        w = np.flatnonzero(悪取[:, i]); 初.append(int(w[0]) if len(w) else len(A))
    return float(np.median(初)), float(悪取[:終わり - 始め].sum(0).mean())
def 測る(s, k):
    o = 一生(s, '見る', 'v4', 種類=(4000,), k代理=k); g, b = 別々(o, 4000, 4600); g0, b0 = 別々(o, 3000, 4000); 初, 回 = 痛い目(o)
    A, 物 = o['行動列'][4000:4600], o['物'][4000:4600]; 取 = A == 0; 悪割 = float((取 & (物 == -1)).sum() / max(1, 取.sum()))   # 取った物のうち悪い物の割合（＝見本のうち悪い結果の割合のめやす）
    return g, b, g0, b0, 初, 回, float(o['食列'][4000:4600].mean()), 悪割, o['sha256']
